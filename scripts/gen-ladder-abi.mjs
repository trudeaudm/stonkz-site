#!/usr/bin/env node
// Emit app/abi/ladderFactory.ts and app/abi/ladderAuction.ts from FORGE ARTIFACTS rather than by hand.
//
// Why generated: app/abi/NOTES.md treats ABI drift as a live hazard — a params tuple's field order is
// ABI-critical, and deployed bytecode has diverged from HEAD before. Transcribing a ~60-member interface by
// hand is how that drift starts. These two files are reproducible from the compiled artifact instead.
//
//   npm run gen:ladder-abi
//
// Re-run after ANY change to the ladder contracts, and re-check the topic0 anchors: the emitted anchors mirror
// the site's existing scanner discipline (a scanner refuses to run when its event signature no longer hashes
// to the anchor), so a silent event-shape change cannot quietly produce an empty index.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { keccak256, stringToHex } from 'viem';

const OUT_DIR = process.env.FORGE_OUT ?? '../stonkz/contracts/out';
const SITE_ABI = new URL('../app/abi/', import.meta.url);

function loadAbi(contract) {
  const p = `${OUT_DIR}/${contract}.sol/${contract}.json`;
  if (!existsSync(p)) {
    throw new Error(`artifact not found: ${p}\nRun \`forge build\` in stonkz/contracts first, or set FORGE_OUT.`);
  }
  return JSON.parse(readFileSync(p, 'utf8')).abi;
}

function canonicalType(input) {
  if (input.type.startsWith('tuple')) {
    return `(${input.components.map(canonicalType).join(',')})${input.type.slice('tuple'.length)}`;
  }
  return input.type;
}

const signatureOf = (entry) => `${entry.name}(${(entry.inputs ?? []).map(canonicalType).join(',')})`;
const topic0 = (sig) => keccak256(stringToHex(sig));

// Never surfaced to the UI. clearAllForTest/clearNextForTest are onlyOwner fast-forwards — a factory-filed
// auction is owned by the factory so they are already unreachable in production, but keeping them out of the
// ABI keeps them out of reach of a future button too.
const FN_DENY = new Set([
  'clearAllForTest',
  'clearNextForTest',
  'setSettlement',
  'setWeightsRef',
  'transferOwnership',
]);

const AUCTION_WRITES = new Set(['placeBid', 'poke', 'claimTokens', 'claimRefund', 'settle', 'start']);
const FACTORY_WRITES = new Set(['file']);

function pick(abi, writes) {
  return abi.filter((e) => {
    if (e.type === 'error' || e.type === 'event') return true;
    if (e.type !== 'function') return false;
    if (FN_DENY.has(e.name)) return false;
    const isRead = e.stateMutability === 'view' || e.stateMutability === 'pure';
    return isRead || writes.has(e.name);
  });
}

function emit(file, exportName, abi, header, anchors) {
  const body = JSON.stringify(abi, null, 2)
    .split('\n')
    .map((l, i) => (i === 0 || !l.trim() ? l : `  ${l}`))
    .join('\n');
  const anchorLines = Object.entries(anchors)
    .map(
      ([name, sig]) =>
        `/** topic0 of \`${sig}\` — anchor so a scanner refuses to run against a drifted ABI. */\n` +
        `export const ${name}: \`0x\${string}\` =\n  '${topic0(sig)}'\n`,
    )
    .join('\n');
  const out = `${header}\nexport const ${exportName} = ${body} as const\n\n${anchorLines}`;
  writeFileSync(new URL(file, SITE_ABI), out.replace(/\r?\n/g, '\n'), 'utf8');
  const counts = abi.reduce((a, e) => ((a[e.type] = (a[e.type] ?? 0) + 1), a), {});
  console.log(`${file.padEnd(20)} ${JSON.stringify(counts)}`);
}

const factoryAbi = loadAbi('StonkzLadderFactory');
const auctionAbi = loadAbi('StonkzLadderAuction');

const need = (abi, name, where) => {
  const e = abi.find((x) => x.type === 'event' && x.name === name);
  if (!e) throw new Error(`event ${name} missing from ${where} artifact`);
  return signatureOf(e);
};

emit(
  'ladderFactory.ts',
  'ladderFactoryAbi',
  pick(factoryAbi, FACTORY_WRITES),
  `/**
 * Ladder factory ABI — GENERATED by scripts/gen-ladder-abi.mjs. Do not hand-edit.
 *
 * \`AuctionFiled\` is the discovery event: index it the way scanner.ts indexes \`ExpressListed\`.
 *
 * Filing is gated by DeployControls (\`_requireDeployAllowed\`), so \`file\` is reachable only by an
 * allowlisted deployer — do NOT build a public "create auction" form against it. The production overload is
 * \`file(params, userSalt)\`, which additionally requires the predicted auction address to carry the 0x4663
 * vanity prefix (16 bits, so cheap to mine client-side, unlike the hook's 30).
 */
`,
  { LADDER_AUCTION_FILED_TOPIC0: need(factoryAbi, 'AuctionFiled', 'factory') },
);

emit(
  'ladderAuction.ts',
  'ladderAuctionAbi',
  pick(auctionAbi, AUCTION_WRITES),
  `/**
 * Ladder auction ABI — GENERATED by scripts/gen-ladder-abi.mjs. Do not hand-edit.
 *
 * Full read surface plus the writes a bidder needs: placeBid, poke, claimTokens, claimRefund, settle, start.
 * Owner-only setters and the onlyOwner \`*ForTest\` fast-forwards are deliberately excluded.
 *
 * Units, because they are the easy thing to get wrong here:
 *  - \`placeBid(size, maxPrice)\`: \`size\` is RAW pair units (wei on a native book, 6dp on USDG) and must be
 *    forwarded as msg.value on a native book. \`maxPrice\` is pair-wei per token, WAD.
 *  - \`minBidPair\` is the $5 minimum ALREADY converted into this book's pair currency. Validate a bid
 *    against it; never against a hardcoded 5e18, which on a native book would mean 5 ETH.
 *  - \`pathPrice\` / \`pathOffered\` / \`pathSold\` are per-period and map straight onto LadderGrid's
 *    LadderPeriodCell { period, price, offered, sold }.
 *  - \`fillOf(wallet)\` returns (committed, spent, tokens, refund) — everything a "my bid" panel needs.
 */
`,
  {
    LADDER_PERIOD_CLEARED_TOPIC0: need(auctionAbi, 'PeriodCleared', 'auction'),
    LADDER_BID_PLACED_TOPIC0: need(auctionAbi, 'BidPlaced', 'auction'),
  },
);
